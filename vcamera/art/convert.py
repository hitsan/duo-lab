"""Turn the black-and-white face drawing into face_art.h: the face without its mouth, and the mouth alone.

Usage (Pillow from nix):
  nix shell --impure --expr 'with import <nixpkgs> {}; python3.withPackages (p: [ p.pillow ])' \
      -c python3 art/convert.py art/face.png > art/face_art.h
"""
import sys
from collections import deque

from PIL import Image

SIZE = 240  # fills the 240-line UVC frame


def load_ink(path):
    image = Image.open(path).convert("L").resize((SIZE, SIZE), Image.Resampling.BOX)
    return [[image.getpixel((x, y)) < 128 for x in range(SIZE)] for y in range(SIZE)]


def components(ink):
    seen = [[False] * SIZE for _ in range(SIZE)]
    found = []
    for y in range(SIZE):
        for x in range(SIZE):
            if ink[y][x] and not seen[y][x]:
                pixels = []
                queue = deque([(x, y)])
                seen[y][x] = True
                while queue:
                    px, py = queue.popleft()
                    pixels.append((px, py))
                    for nx, ny in ((px + 1, py), (px - 1, py), (px, py + 1), (px, py - 1)):
                        if 0 <= nx < SIZE and 0 <= ny < SIZE and ink[ny][nx] and not seen[ny][nx]:
                            seen[ny][nx] = True
                            queue.append((nx, ny))
                found.append(pixels)
    return found


def find_mouth(found):
    """The outline is the largest blob; of the rest the mouth sits lowest"""
    others = sorted(found, key=len)[:-1]
    return max(others, key=lambda pixels: sum(y for _, y in pixels) / len(pixels))


def bitmap_rows(ink, left, top, width, height):
    """One row per line, packed MSB first"""
    rows = []
    for y in range(top, top + height):
        row = []
        for start in range(left, left + width, 8):
            byte = 0
            for bit in range(8):
                x = start + bit
                if x < left + width and ink[y][x]:
                    byte |= 0x80 >> bit
            row.append(byte)
        rows.append(row)
    return rows


def print_array(name, rows):
    print(f"static const uint8_t {name}[] = {{")
    for row in rows:
        print("    " + ", ".join(f"0x{byte:02X}" for byte in row) + ",")
    print("};")


def main():
    ink = load_ink(sys.argv[1])
    mouth = find_mouth(components(ink))
    xs = [x for x, _ in mouth]
    ys = [y for _, y in mouth]
    left, top = min(xs), min(ys)
    width, height = max(xs) - left + 1, max(ys) - top + 1

    mouth_ink = [[False] * SIZE for _ in range(SIZE)]
    for x, y in mouth:
        ink[y][x] = False
        mouth_ink[y][x] = True

    print("#ifndef FACE_ART_H\n#define FACE_ART_H\n\n#include <stdint.h>\n")
    print(f"/* Generated by art/convert.py from {sys.argv[1].split('/')[-1]}. 1 bit per pixel, MSB first, 1 = ink */")
    print(f"#define FACE_ART_SIZE {SIZE}")
    print(f"#define FACE_ART_MOUTH_LEFT {left}")
    print(f"#define FACE_ART_MOUTH_TOP {top}")
    print(f"#define FACE_ART_MOUTH_WIDTH {width}")
    print(f"#define FACE_ART_MOUTH_HEIGHT {height}\n")
    print("/* The face with its mouth erased */")
    print_array("FACE_ART", bitmap_rows(ink, 0, 0, SIZE, SIZE))
    print("\n/* The open mouth alone, cut to its bounding box */")
    print_array("FACE_ART_MOUTH", bitmap_rows(mouth_ink, left, top, width, height))
    print("\n#endif")


main()
